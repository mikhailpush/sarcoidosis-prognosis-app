# 6. МАТЕМАТИЧЕСКИЙ РАСЧЕТ P0 И P1
# =============================================================================
rows = []
prod_a = 1.0
prod_b = 1.0

sorted_keys = sorted(predictors.keys(), key=lambda k: predictors[k]["num"])

for key in sorted_keys:
    item = predictors[key]
    chosen_code = st.session_state[key]
    desc, ai, bi = item["options"][chosen_code]
    prod_a *= ai
    prod_b *= bi
    rows.append({
        "№": str(item["num"]),
        "Показатель": item["title"].split(". ", 1)[1],
        "Выбранная градация": desc,
        "Код": "Пропуск" if chosen_code == -1 else str(chosen_code),
        "Вероятность неблагопр. (Ai)": ai,
        "Вероятность благопр. (Bi)": bi,
        "Отношение Ai / Bi": round(ai / bi, 2) if bi > 0 else 0
    })

P0 = M0 * prod_a
P1 = M1 * prod_b

total_p = P0 + P1
rel_p0 = (P0 / total_p) * 100 if total_p > 0 else 50.0
rel_p1 = (P1 / total_p) * 100 if total_p > 0 else 50.0

if submit_btn:
    verdict_short = "Неблагоприятное (P0 > P1)" if P0 > P1 else "Благоприятное (P0 < P1)"
